def e5_table():
    all_cells = cells()
    order = ("frac", "loc", "side", "const")
    title = {"frac": "contamination fraction (outliers at $\\pm10$)", "loc": "outlier location (5\\%)",
             "side": "one-sided outliers", "const": "bisquare constant"}
    paths = sorted(glob.glob(os.path.join(E5, "e5_*.npy")),
                   key=lambda p: (order.index(all_cells[int(os.path.basename(p).split("_")[1])][0]),
                                  int(os.path.basename(p).split("_")[1])))
    core_en = {0: "Gaussian", 1: "Gamma(4)", 2: "Bimodal"}
    rows, last = [], None
    for p in paths:
        idx = int(os.path.basename(p).split("_")[1])
        axis, ci, frac, loc, one_sided, mult = all_cells[idx]
        if axis != last:
            last = axis
            rows.append(rf"\multicolumn{{9}}{{l}}{{\emph{{{title[axis]}}}}} \\")
        res = np.load(p)
        m = res.mean(0)
        r = m / m[0]
        kb = int(np.argmin(m[FIXED]))
        cont = "none" if frac == 0 else rf"{100 * frac:.0f}\% at {'+' if one_sided else r'$\pm$'}{loc:.0f}"
        v, s = ratio_se(res[:, IA], res[:, IM])
        rows.append(f"{core_en[ci]} & {cont} & {mult:.1f} & {f3(r[IM])} & {f3(r[I1])} & "
                    f"{f3(r[K0 + kb])} & {f3(r[IA])} & {f3(r[IT])}/{f3(r[IW])} & {v:.3f} ({s:.3f}) \\\\")
    write("e5.tex", rel(E5), tabular(
        "llccccccc",
        [r"Core & outliers & $c/4.685$ & M & $a=1$ & best $a$ & selected & Newey T6/W6 & selected/M \\"],
        rows))


