def tabular(spec, head, rows):
    return "\n".join([rf"\begin{{tabular}}{{{spec}}}", r"\toprule", *head, r"\midrule",
                      *rows, r"\bottomrule", r"\end{tabular}"])


# ---------------------------------------------------------------- parsing of printed tables
def parse(path, stop=None):
    """{N: [(english label, [numbers])]} from a printed table with '=== N = ... ===' blocks."""
    blocks, n = {}, None
    for line in open(path):
        if stop and stop in line:
            break
        m = re.match(r"=== N = (\d+)", line)
        if m:
            n = int(m.group(1))
            blocks[n] = []
            continue
        toks = line.replace("|", " ").split()
        k = next((i for i, t in enumerate(toks) if NUM.match(t)), None)
        if n is None or k is None or k == 0:
            continue
        label = " ".join(toks[:k])
        if label in EN and all(NUM.match(t) for t in toks[k:]):
            blocks[n].append((EN[label], [float(t) for t in toks[k:]]))
    return blocks


def f3(v):
    return f"{v:.3f}"


# ---------------------------------------------------------------- E7: all laws, all N
def load_e7():
    out = {}
    for path in glob.glob(os.path.join(E7, "t1_*.npy")):
        li, n, R = (int(v) for v in os.path.basename(path)[3:-4].split("_"))
        apath = os.path.join(E7, f"asm_{li}_{n}_{R}.txt")
        asm = np.genfromtxt(apath, skip_header=1)[:, 0] if os.path.exists(apath) else None
        out[(li, n)] = (np.load(path), asm, R)
    return out


def e7_tables(e7):
    ns = sorted({n for _, n in e7})
    lab = {li: EN.get(name, name) for li, (name, _) in enumerate(LAWS)}
    rows, rows_fix, rows_pair = [], [], []
    worst = (0, None)
    t3 = {}
    for n in ns:
        R = e7[(0, n)][2]
        rows.append(rf"\multicolumn{{8}}{{l}}{{\emph{{$N={n}$, $R={R}$}}}} \\")
        rows_fix.append(rf"\multicolumn{{9}}{{l}}{{\emph{{$N={n}$}}}} \\")
        rows_pair.append(rf"\multicolumn{{6}}{{l}}{{\emph{{$N={n}$}}}} \\")
        for li in range(len(LAWS)):
            res, asm, _ = e7[(li, n)]
            m = res.mean(0)
            r = m / m[0]
            kb = int(np.argmin(m[FIXED]))
            a = "--"
            if asm is not None:
                ok = ~np.isnan(asm)
                a = f3(asm[ok].mean() / res[ok, 0].mean())
            rows.append(f"{lab[li]} & {f3(r[IM])} & {f3(r[I1])} & {f3(r[K0 + kb])} ({GRID[kb]:g}) & "
                        f"{f3(r[IA])} ({m[IAL]:.2f}) & {f3(r[IT])} & {f3(r[IW])} & {a} \\\\")
            rows_fix.append(f"{lab[li]} & " + " & ".join(f3(v) for v in r[FIXED]) + r" \\")
            pr = [ratio_se(res[:, IA], res[:, K0 + kb]), ratio_se(res[:, IA], res[:, I1]),
                  ratio_se(res[:, IA], res[:, IT]), ratio_se(res[:, IA], res[:, IW])]
            if asm is not None:
                ok = ~np.isnan(asm)
                pr.append(ratio_se(res[ok, IA], asm[ok]))
            cells_ = [f"{v:.3f} ({s:.3f})" for v, s in pr] + ["--"] * (5 - len(pr))
            rows_pair.append(f"{lab[li]} & " + " & ".join(cells_) + r" \\")
            ex = m[IA] / m[FIXED].min() - 1
            if ex > worst[0]:
                worst = (ex, (LAWS[li][0], n))
            if LAWS[li][0] == "t3":
                arms = [m[K0 + kb], m[IA], m[IT], m[IW], m[I1]]
                if asm is not None:
                    arms.append(asm[ok].mean() / res[ok, 0].mean() * m[0])
                t3[n] = 1 - min(arms) / m[IM]
    src = rel(E7)
    write("e7_main.tex", src, tabular(
        "lccccccc",
        [r" & & \multicolumn{3}{c}{Fractional basis} & \multicolumn{2}{c}{Newey, $J=6$} & \\",
         r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
         r"Error law & M & $a=1$ & best $a$ & selected $\hat a$ & transf. & weighted & \texttt{asm} \\"],
        rows))
    write("e7_fixed.tex", src, tabular(
        "l" + "c" * len(GRID),
        ["Error law & " + " & ".join(f"$a={a:g}$" for a in GRID) + r" \\"], rows_fix))
    write("e7_paired.tex", src, tabular(
        "lccccc",
        [r"Error law & best fixed $a$ & $a=1$ & Newey transf. & Newey weighted & \texttt{asm} \\"],
        rows_pair))
    print(f"E7: largest excess of the selected exponent over the best fixed one: {100 * worst[0]:.1f}% at {worst[1]}")
    print("E7: t3, largest gain of any arm over M by N:", {n: f"{100 * v:.1f}%" for n, v in t3.items()})


