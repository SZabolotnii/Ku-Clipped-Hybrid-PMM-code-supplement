# ---------------------------------------------------------------- selector: population and prediction test
def parse_pop(path):
    blocks, cur = {}, None
    bias = []
    for line in open(path):
        m = re.match(r"=== N = (\d+), delta = ([\d.]+)", line)
        if m:
            cur = int(m.group(1))
            blocks[cur] = {"delta": float(m.group(2))}
            continue
        toks = line.split()
        if cur is not None and toks and toks[0] in ("alpha", "ideal", "crit", "real", "rho"):
            blocks[cur][toks[0]] = [float(t) for t in toks[1:]]
        m = re.match(r"criterion selects alpha = ([\d.]+); smallest real variance at alpha = ([\d.]+); lag = ([\d.]+)", line)
        if m and cur is not None:
            blocks[cur]["sel"], blocks[cur]["best"], blocks[cur]["lag"] = (float(g) for g in m.groups())
        m = re.match(r"delta =\s+([\d.]+)\s+relative bias = (-?[\d.]+)(?:\s+local exponent ([\d.]+))?", line)
        if m:
            bias.append((float(m.group(1)), float(m.group(2)), m.group(3)))
        m = re.search(r"expected exponent p \+ beta = ([\d.]+)", line)
        if m:
            expected = float(m.group(1))
    head = open(path).readline()
    mb = float(re.search(r"bisquare M-estimate / OLS = ([\d.]+)", head).group(1))
    return blocks, bias, expected, mb


