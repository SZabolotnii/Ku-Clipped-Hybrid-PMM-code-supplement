"""Build Table 1 of the Letter and the claim ledger from the stored replications.

Usage (from the track root):  python paper/make_tables.py

Reads   results/letter_2026-11-13/e7_per_rep/  (E7: t1_<law>_<N>_<R>.npy, asm_<law>_<N>_<R>.txt)
        results/letter_2026-11-13/e5_per_rep/  (E5: e5_<cell>_<N>_<R>.npy)
Writes  paper/tables/table1.tex
        paper/claims.yaml  (every number of the table and of the running text, with its source;
                            a number whose printed form is not found in the sections is listed
                            with location null)
Nothing is simulated here.
"""
import glob
import math
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from baselines_mc import GRID  # noqa: E402
from sensitivity_mc import CORES, cells  # noqa: E402
from table1_mc import COLS, K0, ratio_se  # noqa: E402

E7 = os.path.join(ROOT, "results", "letter_2026-11-13", "e7_per_rep")
E5 = os.path.join(ROOT, "results", "letter_2026-11-13", "e5_per_rep")
PAPER = os.path.join(ROOT, "paper")

# law index in table1_mc.LAWS -> row label of Table 1
ROWS = [(0, "Gaussian"), (1, "Laplace"), (2, "GG(0.7)"), (5, "Gamma(4)"),
        (6, r"Gaussian + 5\%"), (7, r"Gamma(4) + 5\%"),
        (8, r"Bimodal + 5\%")]
LAW_NAME = {0: "Gaussian", 1: "Laplace", 2: "GG(0.7)", 3: "t3", 4: "bimodal", 5: "Gamma(4)",
            6: "Gaussian+5%", 7: "Gamma(4)+5%", 8: "bimodal+5%"}
FIXED = slice(K0, K0 + len(GRID))
IA, IM = COLS.index("adapt"), COLS.index("M")
IT, IW, IAL = COLS.index("NwT6"), COLS.index("NwW6"), COLS.index("alpha")
I1 = K0 + len(GRID) - 1


def load_e7():
    out = {}
    for path in glob.glob(os.path.join(E7, "t1_*.npy")):
        li, n, R = (int(v) for v in os.path.basename(path)[3:-4].split("_"))
        apath = os.path.join(E7, f"asm_{li}_{n}_{R}.txt")
        asm = np.genfromtxt(apath, skip_header=1)[:, 0] if os.path.exists(apath) else None
        out[(li, n)] = (np.load(path), asm, os.path.relpath(path, ROOT),
                        os.path.relpath(apath, ROOT) if asm is not None else None)
    return out


def asm_rel(res, asm):
    ok = ~np.isnan(asm)
    return asm[ok].mean() / res[ok, 0].mean()


claims = []


def claim(raw, value, context, artifact, locator, kind="artifact"):
    claims.append(dict(raw=raw, value=value, context=context, artifact=artifact, locator=locator,
                       kind=kind))


def table1(e7):
    lines = [r"\begin{tabular}{lccccccc}", r"\toprule",
             r" & & \multicolumn{3}{c}{Fractional basis} & \multicolumn{2}{c}{Newey, $J=6$} & \\",
             r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
             r"Error law & M & $a=1$ & best $a$ & selected $\hat a$ & transf. & weighted & \texttt{asm} \\",
             r"\midrule"]
    for li, label in ROWS:
        res, asm, art, aart = e7[(li, 2000)]
        m = res.mean(0)
        rel = m / m[0]
        kb = int(np.argmin(m[FIXED]))
        vals = [rel[IM], rel[I1], rel[K0 + kb], rel[IA], rel[IT], rel[IW], asm_rel(res, asm)]
        # bold = lowest feasible arm; "best a" is an oracle reference and is never bold
        low = min(round(v, 3) for k, v in enumerate(vals) if k != 2)
        cellstr = []
        for k, v in enumerate(vals):
            s = f"{v:.3f}"
            if k != 2 and round(v, 3) == low:
                s = r"\textbf{" + s + "}"
            if k == 2:
                s += f" ({GRID[kb]:g})"
            if k == 3:
                s += f" ({m[IAL]:.2f})"
            cellstr.append(s)
            col = ["M", "a=1", "best fixed a", "adaptive", "NwT6", "NwW6", "asm"][k]
            claim(f"{v:.3f}", round(float(v), 3), f"Table 1, {LAW_NAME[li]}, column {col}",
                  aart if k == 6 else art, f"mean slope SSE of column {col} / column OLS, N = 2000")
        claim(f"{GRID[kb]:g}", GRID[kb], f"Table 1, {LAW_NAME[li]}, best fixed exponent", art,
              "argmin over the fixed-a columns")
        claim(f"{m[IAL]:.2f}", round(float(m[IAL]), 2), f"Table 1, {LAW_NAME[li]}, mean selected exponent",
              art, "mean of column alpha")
        lines.append(label + " & " + " & ".join(cellstr) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.join(PAPER, "tables"), exist_ok=True)
    with open(os.path.join(PAPER, "tables", "table1.tex"), "w") as f:
        f.write("% generated by paper/make_tables.py from results/letter_2026-11-13/e7_per_rep\n")
        f.write("\n".join(lines) + "\n")


def text_numbers(e7):
    """Numbers quoted in the running text; printed so the prose can be checked against them."""
    print("--- adaptive / integer exponents, paired ratio (se) ---")
    for li in (2, 1):
        for n in (500, 2000, 8000):
            res, _, art, _ = e7[(li, n)]
            r, se = ratio_se(res[:, IA], res[:, I1])
            print(LAW_NAME[li], n, f"{r:.3f} ({se:.3f})  gain {100 * (1 - r):.1f}%")
            claim(f"{100 * (1 - r):.1f}", round(100 * (1 - r), 1),
                  f"gain of the selected exponent over integer exponents, {LAW_NAME[li]}, N = {n} (percent)",
                  art, "1 - mean(adapt)/mean(a=1)", "derived")
    worst = 0.0
    for (li, n), (res, _, art, _) in e7.items():
        m = res.mean(0)
        worst = max(worst, m[IA] / m[FIXED].min() - 1)
    print(f"adaptive over best fixed, worst of {len(e7)} cells: {100 * worst:.1f}%")
    claim(f"{100 * worst:.1f}", round(100 * worst, 1),
          "largest excess of the selected exponent over the best fixed one, all E7 cells (percent)",
          os.path.relpath(E7, ROOT), "max over cells of mean(adapt)/min fixed - 1", "derived")
    print("--- adaptive / Newey and asm at N = 2000 ---")
    for li in (5, 7, 6, 8, 2):
        res, asm, art, aart = e7[(li, 2000)]
        m = res.mean(0)
        ok = ~np.isnan(asm)
        ra = ratio_se(res[ok, IA], asm[ok])[0]
        print(LAW_NAME[li], f"/NwT6 {m[IA] / m[IT]:.3f}  /NwW6 {m[IA] / m[IW]:.3f}  /asm {ra:.3f}")
        for name, v, a in (("NwT6", m[IA] / m[IT], art), ("NwW6", m[IA] / m[IW], art), ("asm", ra, aart)):
            claim(f"{v:.3f}", round(float(v), 3),
                  f"slope MSE ratio adaptive / {name}, {LAW_NAME[li]}, N = 2000", a,
                  f"mean(adapt)/mean({name})", "derived")
    res8 = e7[(2, 8000)][0].mean(0)
    print("GG(0.7), N = 8000: integer", f"{res8[I1] / res8[0]:.3f}", "adaptive", f"{res8[IA] / res8[0]:.3f}",
          "NwT6", f"{res8[IT] / res8[0]:.3f}")
    for name, idx in (("a=1", I1), ("adaptive", IA), ("NwT6", IT)):
        claim(f"{res8[idx] / res8[0]:.3f}", round(float(res8[idx] / res8[0]), 3),
              f"slope MSE / OLS, GG(0.7), N = 8000, column {name}", e7[(2, 8000)][2],
              f"mean({name})/mean(OLS)")
    gains = {}
    for n in (500, 2000, 8000):
        res3, asm3, art3, _ = e7[(3, n)]
        m3 = res3.mean(0)
        arms = [min(m3[FIXED]), m3[IA], m3[IT], m3[IW]]
        if asm3 is not None:
            arms.append(asm_rel(res3, asm3) * m3[0])
        gains[n] = (1 - min(arms) / m3[IM], art3)
    n3 = max(gains, key=lambda n: gains[n][0])
    print("t3: largest gain over M among all arms:", {n: f"{100 * g:.1f}%" for n, (g, _) in gains.items()})
    claim(f"{100 * gains[n3][0]:.1f}", round(100 * gains[n3][0], 1),
          f"largest gain over the M-estimate among all arms, t3, max over N (attained at N = {n3}; percent)",
          gains[n3][1], "1 - min over arms / mean(M)", "derived")
    print("--- E5: cost of the constant x 0.7 without outliers, adaptive / OLS relative to x 1.0 ---")
    by = {}
    for path in glob.glob(os.path.join(E5, "e5_*.npy")):
        idx = int(os.path.basename(path).split("_")[1])
        axis, ci, frac, loc, one_sided, mult = cells()[idx]
        if frac == 0 and mult in (0.7, 1.0):
            res = np.load(path).mean(0)
            by[(ci, mult)] = res[IA] / res[0]
    for ci in range(len(CORES)):
        cost = 100 * (by[(ci, 0.7)] / by[(ci, 1.0)] - 1)
        print(CORES[ci][0], f"{cost:.1f}%")
        claim(f"{cost:.0f}", round(cost, 1),
              f"cost of the bisquare constant x 0.7 without outliers, core {ci} (percent; text quotes the range)",
              os.path.relpath(E5, ROOT), "(adapt/OLS at x0.7) / (adapt/OLS at x1.0) - 1", "derived")
    print("--- E5: adaptive / M over the sensitivity cells ---")
    rng = {}
    for path in glob.glob(os.path.join(E5, "e5_*.npy")):
        idx = int(os.path.basename(path).split("_")[1])
        ci = cells()[idx][1]
        res = np.load(path).mean(0)
        rng.setdefault(ci, []).append(res[IA] / res[IM])
    for ci, v in sorted(rng.items()):
        print(CORES[ci][0], f"{min(v):.3f} .. {max(v):.3f}  ({len(v)} cells)")
        for tag, x in (("smallest", min(v)), ("largest", max(v))):
            claim(f"{x:.2f}", round(float(x), 2),
                  f"{tag} slope MSE ratio adaptive / M over the E5 cells, core {ci}",
                  os.path.relpath(E5, ROOT), "mean(adapt)/mean(M) per cell", "derived")


def write_ledger():
    sections = {}
    for path in sorted(glob.glob(os.path.join(PAPER, "sections", "*.tex"))) + \
            [os.path.join(PAPER, "tables", "table1.tex")]:
        with open(path) as f:
            sections[os.path.relpath(path, PAPER)] = f.read().splitlines()

    def locate(raw, table):
        for name, lines in sections.items():
            if (name.startswith("tables")) != table:
                continue
            for k, line in enumerate(lines, 1):
                if raw in line:
                    return name, k
        return None

    out = ["version: 1", "manuscript: paper/main.tex", 'results_root: ""',
           "generated: 2026-11-13", "claims:"]
    missing = 0
    for k, c in enumerate(claims):
        loc = locate(c["raw"], c["context"].startswith("Table 1"))
        missing += loc is None
        out += [f"  - id: {k:08x}", f'    raw: "{c["raw"]}"', f"    value: {c['value']}",
                f"    context_class: {'table-cell' if c['context'].startswith('Table 1') else 'narrative'}",
                "    location: " + ("null" if loc is None else f"{{ file: {loc[0]}, line: {loc[1]} }}"),
                f'    context: "{c["context"]}"', "    status: resolved", "    evidence:",
                f"      kind: {c['kind']}", f'      artifact: "{c["artifact"]}"',
                f'      locator: "{c["locator"]}"', '      producer: "paper/make_tables.py"',
                "      confidence: high"]
    with open(os.path.join(PAPER, "claims.yaml"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"claims.yaml: {len(claims)} claims; printed form not found in the text for {missing}")


if __name__ == "__main__":
    data = load_e7()
    table1(data)
    text_numbers(data)
    write_ledger()
